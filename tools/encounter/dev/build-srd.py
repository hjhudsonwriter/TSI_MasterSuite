#!/usr/bin/env python3
"""Builds tools/encounter/data/srd-monsters.js from the 5e-bits database (https://github.com/5e-bits/5e-database, MIT; its monster
text is from the System Reference Document, CC BY 4.0). Run once when the data should change; the suite never runs this.

  python3 build-srd.py <5e-SRD-Monsters 2024.json> <5e-SRD-Monsters 2014.json> <out .js>

Every monster of SRD 5.2 (the 2024 rules) is kept. Thug and Veteran are not in SRD 5.2, so they come from SRD 5.1 (marked ed: '2014').
Only what the Combat Tracker's stat block panel shows is kept, in short keys (see tools/encounter/stat-block.js)."""
import json, sys, re

d24 = json.load(open(sys.argv[1])); d14 = json.load(open(sys.argv[2]))

def ent(a):
    o = {'n': a['name'], 'd': a.get('desc', '')}
    u = a.get('usage')
    if u:
        if u['type'] == 'recharge on roll': o['rc'] = u.get('min_value')
        elif u['type'] == 'per day': o['pd'] = u.get('times')
        elif u['type'] == 'per day' and u.get('times_in_lair'): o['pd'] = u['times']
        else: o['us'] = u.get('type')
    return o

def conv(m, ed):
    ac = m['armor_class'][0] if m.get('armor_class') else {'value': 10}
    prof = {}
    for p in m.get('proficiencies', []):
        prof[p['proficiency']['index']] = p['value']
    saves = {k[len('saving-throw-'):]: v for k, v in prof.items() if k.startswith('saving-throw-')}
    skills = {k[len('skill-'):]: v for k, v in prof.items() if k.startswith('skill-')}
    lr = None
    for a in m.get('special_abilities', []):
        if a['name'].startswith('Legendary Resistance'):
            u = a.get('usage') or {}
            lr = u.get('times') or 3
    o = {
        'i': m['index'], 'n': m['name'], 'sz': m.get('size', ''), 't': m.get('type', ''), 'al': m.get('alignment', ''),
        'ac': ac['value'], 'hp': m['hit_points'], 'hd': m.get('hit_points_roll') or m.get('hit_dice', ''),
        'sp': m.get('speed', {}),
        'ab': [m['strength'], m['dexterity'], m['constitution'], m['intelligence'], m['wisdom'], m['charisma']],
        'cr': m.get('challenge_rating', 0), 'xp': m.get('xp', 0), 'pb': m.get('proficiency_bonus', 2),
        'ed': ed
    }
    if ac.get('type'): o['at'] = ac['type']
    if saves: o['sv'] = saves
    if skills: o['sk'] = skills
    for k, key in (('damage_vulnerabilities', 'vu'), ('damage_resistances', 'rs'), ('damage_immunities', 'im')):
        v = m.get(k) or []
        if v: o[key] = v if isinstance(v, list) else [v]
    ci = [c['name'] for c in (m.get('condition_immunities') or [])]
    if ci: o['ci'] = ci
    se = m.get('senses') or {}
    o['se'] = se
    if m.get('languages'): o['lg'] = m['languages']
    for k, key in (('special_abilities', 'tr'), ('actions', 'ac_'), ('bonus_actions', 'ba'), ('reactions', 're')):
        v = m.get(k) or []
        if v: o[key] = [ent(a) for a in v]
    la = m.get('legendary_actions') or []
    if la:
        o['la'] = [{'n': a['name'], 'd': a.get('desc', '')} for a in la]
        o['lan'] = 3
    if lr: o['lr'] = lr
    return o

out = {}
for m in d24:
    out[m['index']] = conv(m, '2024')
for slug in ('thug', 'veteran'):
    if slug not in out:
        out[slug] = conv([x for x in d14 if x['index'] == slug][0], '2014')

js = ("/* The Combat Tracker's stat blocks: every monster of the System Reference Document 5.2 (the 2024 rules), plus Thug and Veteran from SRD 5.1\n"
      "   (they are not in 5.2). Generated by tools/encounter/dev/build-srd.py from the 5e-bits database; do not edit by hand.\n"
      "   Content from the SRD is licensed CC BY 4.0 (see licences/README.md). Keyed by slug ('bandit-captain'). Short keys: n name, sz size, t type,\n"
      "   al alignment, ac armour class (at: its kind), hp, hd hit dice, sp speed, ab abilities [STR, DEX, CON, INT, WIS, CHA], sv saves, sk skills,\n"
      "   vu / rs / im damage vulnerabilities / resistances / immunities, ci condition immunities, se senses, lg languages, cr, xp, pb proficiency\n"
      "   bonus, tr traits, ac_ actions, ba bonus actions, re reactions, la legendary actions (lan: uses a round), lr legendary resistances a day, ed\n"
      "   edition. An action may have rc (recharge on this d6 roll or more) or pd (uses a day). */\n"
      "window.TSI_DATA = window.TSI_DATA || {};\nwindow.TSI_DATA.srdMonsters = ") + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ";\n"
open(sys.argv[3], 'w').write(js)
print(len(out), 'monsters,', len(js) // 1024, 'KB')
